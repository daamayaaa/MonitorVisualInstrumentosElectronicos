package com.damaya.proyinv.dto;

public class EstadisticasBalanzaDTO {
	private double totalPeso;
	private double maximoPeso;
	private double minimoPeso;
	private double promedioPeso;
	private double medianaPeso;
	private double modaPeso;
	
	public double getTotalPeso() {
		return totalPeso;
	}
	
	public void setTotalPeso(double totalPeso) {
		this.totalPeso = totalPeso;
	}
	
	public double getMaximoPeso() {
		return maximoPeso;
	}
	
	public void setMaximoPeso(double maximoPeso) {
		this.maximoPeso = maximoPeso;
	}
	
	public double getMinimoPeso() {
		return minimoPeso;
	}
	
	public void setMinimoPeso(double minimoPeso) {
		this.minimoPeso = minimoPeso;
	}
	
	public double getPromedioPeso() {
		return promedioPeso;
	}
	
	public void setPromedioPeso(double promedioPeso) {
		this.promedioPeso = promedioPeso;
	}
	
	public double getMedianaPeso() {
		return medianaPeso;
	}
	
	public void setMedianaPeso(double medianaPeso) {
		this.medianaPeso = medianaPeso;
	}
	
	public double getModaPeso() {
		return modaPeso;
	}
	
	public void setModaPeso(double modaPeso) {
		this.modaPeso = modaPeso;
	}
}